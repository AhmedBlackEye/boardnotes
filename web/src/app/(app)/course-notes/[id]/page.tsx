"use client";
import { useParams } from "next/navigation";
import { useState } from "react";
import { Button } from "@/components/Button";
import { Icon } from "@/components/Icon";
import { Math as Tex } from "@/components/Math";
import { StatusPill } from "@/components/StatusPill";
import { TopBar } from "@/components/TopBar";
import type { LectureDetail } from "@/contracts/LectureDetail";
import type { Section } from "@/contracts/Section";
import { assetUrl } from "@/lib/api";
import { api } from "@/lib/client";
import { cx } from "@/lib/cx";
import { formatAgo } from "@/lib/format";
import { useAsync } from "@/lib/hooks";

/** Group sections into pages of two, mirroring how the PDF lays them out. */
function paginate(sections: Section[]): Section[][] {
  const pages: Section[][] = [];
  for (let i = 0; i < sections.length; i += 2) pages.push(sections.slice(i, i + 2));
  return pages.length ? pages : [[]];
}

function Page({ lecture, sections, n, total }: { lecture: LectureDetail; sections: Section[]; n: number; total: number }) {
  return (
    <div className="mx-auto flex aspect-[1/1.35] w-full max-w-[400px] flex-col gap-4 bg-surface p-8 text-primary shadow-panel" data-testid="pdf-page">
      <div className="flex justify-between text-[10px] text-tertiary">
        <span>Linear Algebra · {lecture.summary.title.split(" · ")[0]}</span>
        {lecture.summary.status === "verified" && <span className="text-success">Verified by lecturer</span>}
      </div>
      {n === 1 && <span className="text-[10px] text-accent underline">Watch the lecture video</span>}
      {sections.map((s) => (
        <div key={s.id} className="flex flex-col gap-2">
          <div className="flex items-center justify-between gap-2">
            <h3 className="text-[13px] font-semibold">
              {s.order} {s.heading}
            </h3>
            {s.status !== "verified" && (
              <span className="rounded-sm border border-warning px-1.5 py-0.5 text-[8px] font-bold uppercase tracking-[0.08em] text-warning">Draft · not yet verified</span>
            )}
          </div>
          {s.bullets.map((b) => (
            <div key={b.id} className="flex items-start justify-between gap-2 text-[11px] leading-4">
              <div>
                <p>{b.text}</p>
                {b.latex && (
                  <div className="py-1 text-center">
                    <Tex latex={b.latex} display />
                  </div>
                )}
              </div>
            </div>
          ))}
        </div>
      ))}
      <div className="flex-1" />
      <div className="flex justify-between text-[9px] text-tertiary">
        <span>Generated by BoardNotes from the lecture recording</span>
        <span>
          Page {n} of {total}
        </span>
      </div>
    </div>
  );
}

export default function PdfPreviewPage() {
  const { id } = useParams<{ id: string }>();
  const isModule = id === "module";
  const pdfs = useAsync(() => api.listPdfs(), []);
  const lecture = useAsync(() => (isModule ? Promise.resolve(null) : api.getLecture(id)), [id]);
  const lectures = useAsync(() => api.listLectures(), []);
  const [page, setPage] = useState(0);

  const info = pdfs.data?.find((p) => (isModule ? p.lecture_id === null : p.lecture_id === id));
  const d = lecture.data;
  const pages = d ? paginate(d.sections) : [];
  const title = isModule ? "Linear Algebra · complete notes.pdf" : `${d?.summary.title ?? "Notes"}.pdf`;
  const url = assetUrl(info?.url) ?? "#";
  const tex = assetUrl(api.texUrl(isModule ? null : id)); // null in live mode until the server has a .tex route
  const verified = d ? d.sections.filter((s) => s.status === "verified").length : 0;

  return (
    <>
      <TopBar
        crumb="Course notes"
        title={title}
        actions={
          <>
            {tex && (
              <a href={tex} download>
                <Button variant="secondary">Download LaTeX</Button>
              </a>
            )}
            <a href={url} download>
              <Button>Download PDF</Button>
            </a>
          </>
        }
      />
      <div className="grid gap-6 p-8 lg:grid-cols-[80px_1fr_280px]">
        <div className="hidden flex-col gap-3 lg:flex" aria-label="Pages">
          {pages.map((_, i) => (
            <button
              key={i}
              type="button"
              onClick={() => setPage(i)}
              aria-label={`Page ${i + 1}`}
              className={cx("flex h-[80px] flex-col gap-1 rounded-sm border bg-surface p-2", i === page ? "border-2 border-accent" : "border-default")}
            >
              {[90, 70, 80, 50].map((w, j) => (
                <span key={j} className="h-1 rounded-full bg-muted" style={{ width: `${w}%` }} />
              ))}
              <span className="mt-auto text-[10px] text-tertiary">{i + 1}</span>
            </button>
          ))}
        </div>
        <div className="rounded-xl bg-muted p-6">
          {isModule ? (
            <div className="mx-auto flex max-w-[400px] flex-col gap-3 bg-surface p-8 text-primary shadow-panel">
              <h3 className="text-[15px] font-semibold">Linear Algebra · complete notes</h3>
              <p className="text-[11px]">Contents</p>
              <ol className="flex flex-col gap-1 text-[11px]">
                {(lectures.data ?? [])
                  .filter((l) => l.status !== "processing" && l.status !== "uploading")
                  .map((l) => (
                    <li key={l.id} className="flex justify-between">
                      <span>{l.title}</span>
                      {l.status !== "verified" && <span className="text-warning">Draft</span>}
                    </li>
                  ))}
              </ol>
            </div>
          ) : d && pages[page] ? (
            <Page lecture={d} sections={pages[page]} n={page + 1} total={pages.length} />
          ) : (
            <p className="text-[13px] text-secondary">{lecture.error ?? "Loading preview…"}</p>
          )}
        </div>
        <div className="flex h-fit flex-col gap-3 rounded-lg border border-default bg-surface p-5 shadow-card">
          <h2 className="font-display text-[15px] font-medium text-primary">About this PDF</h2>
          <dl className="flex flex-col gap-3 text-[13px]">
            <div className="flex items-center justify-between">
              <dt className="text-secondary">Status</dt>
              <dd>{info?.status === "verified" ? <StatusPill status="verified" /> : <StatusPill status="in_review">Partly verified</StatusPill>}</dd>
            </div>
            <div className="flex justify-between">
              <dt className="text-secondary">Pages</dt>
              <dd className="font-semibold text-primary">{info?.pages ?? "–"}</dd>
            </div>
            <div className="flex justify-between">
              <dt className="text-secondary">Generated</dt>
              <dd className="font-semibold text-primary">{info ? formatAgo(info.generated_at) : "–"}</dd>
            </div>
            {d && (
              <div className="flex justify-between">
                <dt className="text-secondary">Sections verified</dt>
                <dd className="font-semibold text-primary">
                  {verified} of {d.sections.length}
                </dd>
              </div>
            )}
          </dl>
          <div className="border-t border-default pt-3">
            <p className="mb-2 text-[11px] font-bold uppercase tracking-[0.08em] text-tertiary">Included</p>
            <ul className="flex flex-col gap-2 text-[13px] text-primary">
              {["Notes and formulas", "Board snapshots", "Link to the lecture video", "Draft marks on unverified sections"].map((t) => (
                <li key={t} className="flex items-center gap-2">
                  <Icon name="check" size={16} className="text-success" />
                  {t}
                </li>
              ))}
            </ul>
          </div>
        </div>
      </div>
    </>
  );
}
