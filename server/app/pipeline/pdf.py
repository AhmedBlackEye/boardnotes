from .chart_svg import chart_svg

TEMPLATES_DIR = Path(__file__).parent / "templates"
KATEX_DIR = REPO_ROOT / "web" / "node_modules" / "katex" / "dist"
TOKENS_CSS = REPO_ROOT / "web" / "src" / "styles" / "tokens.css"
MERMAID_JS = REPO_ROOT / "web" / "node_modules" / "mermaid" / "dist" / "mermaid.min.js"
MAX_CROP_BYTES = 3_000_000  # board crops are embedded in the page; skip anything unexpectedly large
DIAGRAMS_TIMEOUT_S = 20.0
log = logging.getLogger(__name__)
FOOTER_TEXT = "Generated by BoardNotes from the lecture recording"
RENDER_TIMEOUT_S = 120.0
MAX_MODULE_LECTURES = 60  # a module PDF renders every lecture in one page; bound the work per request
_RENDER_SLOTS = asyncio.Semaphore(2)  # each render starts its own Chromium; cap how many run at once

_env = Environment(loader=FileSystemLoader(TEMPLATES_DIR), autoescape=select_autoescape(["html"]), trim_blocks=True, lstrip_blocks=True)


# ---------- small pure helpers ----------
def format_time(seconds: float) -> str:
    """Seconds -> 'mm:ss' (or 'h:mm:ss' past an hour). Only for display."""
    total = max(0, int(seconds))
    h, rest = divmod(total, 3600)
    m, s = divmod(rest, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m:02d}:{s:02d}"


def safe_video_url(url: str) -> str | None:
    """Return an absolute http(s) URL that is safe to put in a PDF link, or None.

    Accepts http(s) URLs and site-relative paths ("/lectures/..."), which are resolved against
    settings.public_base_url so the PDF never contains links that resolve against file://.
    Rejects backslashes, whitespace and control characters outright: browsers and PDF viewers
    normalise them differently from urlsplit (e.g. "/\\evil.com" becomes a host), so they're never needed.
    """
    url = url.strip()
    if not url or "\\" in url or any(c.isspace() or ord(c) < 32 or ord(c) == 127 for c in url):
        return None
    parts = urlsplit(url)
    if parts.scheme in ("http", "https") and parts.netloc:
        return url
    if not parts.scheme and not parts.netloc and url.startswith("/") and not url.startswith("//"):
        absolute = urljoin(settings.public_base_url.rstrip("/") + "/", url.lstrip("/"))
        resolved = urlsplit(absolute)
        return absolute if resolved.scheme in ("http", "https") and resolved.netloc else None
    return None


def timestamp_link(video_url: str | None, seconds: float) -> str | None:
    if video_url is None:
        return None
    base = video_url.split("#", 1)[0]
    return f"{base}#t={round(max(0.0, seconds), 1):g}"


def bullet_time(bullet: Bullet, first_seen: dict[str, float]) -> float | None:
    """The bullet's first source moment: earliest transcript range, else earliest cited board block."""
    if bullet.transcript_ranges:
        return min(r.start_s for r in bullet.transcript_ranges)
    seen = [first_seen[b] for b in bullet.board_block_ids if b in first_seen]
    return min(seen) if seen else None


def status_label(status: LectureStatus) -> str:
    return {
        LectureStatus.VERIFIED: "Verified by the lecturer",
        LectureStatus.IN_REVIEW: "In review · not yet verified",
    }.get(status, "Draft · not yet verified")


@cache
def design_tokens() -> dict[str, str]:
    """Light-theme custom properties from web/src/styles/tokens.css (the first :root block)."""
    try:
        css = TOKENS_CSS.read_text()
    except OSError as exc:
        log.warning("design tokens unavailable (%s); PDF uses fallback colours", exc)
        return {}
    block = css.split("}", 1)[0]
    return dict(re.findall(r"(--[\w-]+):\s*([^;]+);", block))


def _token(name: str, fallback: str) -> str:
    return design_tokens().get(name, fallback)


# ---------- view models ----------
@dataclass
class FigureView:
    """A diagram under the bullet that cites it. svg is built by chart_svg (escaped); crop is a data: URI we built."""

    kind: str  # "chart" | "mermaid" | "crop"
    caption: str
    redrawn_by_ai: bool
    svg: Markup | None = None
    mermaid: str | None = None
    crop: str | None = None


@dataclass
class BulletView:
    text: str
    latex: str | None
    uncertain: bool
    time: str | None
    link: str | None
    figures: list[FigureView] = field(default_factory=list)


@dataclass
class SaidView:
    text: str
    time: str
    link: str | None


@dataclass
class SectionView:
    number: int
    heading: str
    draft: bool
    bullets: list[BulletView]
    said: list[SaidView]


@dataclass
class LectureView:
    title: str
    status: LectureStatus
    status_label: str
    duration: str | None
    verified_sections: int
    total_sections: int
    sections: list[SectionView] = field(default_factory=list)


@dataclass
class CoverView:
    title: str
    lecture_count: int
    verified_count: int

    @property
    def verified_percent(self) -> int:
        return round(100 * self.verified_count / self.lecture_count) if self.lecture_count else 0


def crop_data_uri(lecture_id: str, block_id: str) -> str | None:
    """The cached board crop of a block (written by the job runner / snapshots route) as a data: URI, or None."""
    if not (is_safe_id(lecture_id) and is_safe_id(block_id)):
        return None
    path = lecture_dir(settings.data_dir, lecture_id) / "snapshots" / f"{block_id}.jpg"
    try:
        if not path.is_file() or path.stat().st_size > MAX_CROP_BYTES:
            return None
        return "data:image/jpeg;base64," + base64.b64encode(path.read_bytes()).decode("ascii")
    except OSError:
        return None


def figure_view(lecture_id: str, block: BoardBlock) -> FigureView | None:
    fig = block.figure
    if fig is None:
        return None
    crop = crop_data_uri(lecture_id, block.id)
    if fig.kind == "chart" and fig.chart is not None:
        svg = Markup(chart_svg(fig.chart, uid=f"fig-{lecture_id}-{block.id}"))  # noqa: S704 - chart_svg escapes all text
        return FigureView(kind="chart", caption=fig.caption, redrawn_by_ai=fig.redrawn_by_ai, svg=svg)
    if fig.kind == "mermaid" and fig.mermaid:
        return FigureView(kind="mermaid", caption=fig.caption, redrawn_by_ai=fig.redrawn_by_ai, mermaid=fig.mermaid, crop=crop)
    return FigureView(kind="crop", caption=fig.caption, redrawn_by_ai=False, crop=crop)


def _section_view(
    number: int,
    section: Section,
    video_url: str | None,
    first_seen: dict[str, float],
    figures: dict[str, FigureView] | None = None,
) -> SectionView:
    """`figures` maps diagram block id -> figure; each is shown once, under the first bullet citing it (and removed)."""
    figures = figures if figures is not None else {}
    bullets: list[BulletView] = []
    for b in sorted(section.bullets, key=lambda b: b.order):
        t = bullet_time(b, first_seen)
        bullets.append(
            BulletView(
                text=b.text,
                latex=b.latex.strip() if b.latex and b.latex.strip() else None,
                uncertain=b.uncertain,
                time=format_time(t) if t is not None else None,
                link=timestamp_link(video_url, t) if t is not None else None,
                figures=[figures.pop(i) for i in b.board_block_ids if i in figures],
            )
        )
    said = [SaidView(text=n.text, time=format_time(n.at_s), link=timestamp_link(video_url, n.at_s)) for n in section.said_not_written]
    return SectionView(number=number, heading=section.heading, draft=section.status != SectionStatus.VERIFIED, bullets=bullets, said=said)


def lecture_view(lecture: LectureDetail, include_drafts: bool = True) -> LectureView:
    video_url = safe_video_url(lecture.video_url)
    first_seen = {b.id: b.first_seen_s for b in lecture.board_blocks}
    figures = {b.id: f for b in lecture.board_blocks if (f := figure_view(lecture.summary.id, b)) is not None}
    ordered = sorted(lecture.sections, key=lambda s: s.order)
    # Numbers follow the full lecture so they match the web app even when drafts are left out.
    sections = [
        _section_view(i, s, video_url, first_seen, figures)
        for i, s in enumerate(ordered, start=1)
        if include_drafts or s.status == SectionStatus.VERIFIED
    ]
    duration = lecture.summary.duration_s
    return LectureView(
        title=lecture.summary.title,
        status=lecture.summary.status,
        status_label=status_label(lecture.summary.status),
        duration=format_time(duration) if duration else None,
        verified_sections=sum(s.status == SectionStatus.VERIFIED for s in ordered),
        total_sections=len(ordered),
        sections=sections,
    )


def _asset(path: Path) -> str | None:
    return path.as_uri() if path.exists() else None


def _render(doc_title: str, lectures: list[LectureView], cover: CoverView | None) -> str:
    if not (KATEX_DIR / "katex.min.js").exists():
        log.warning("KaTeX not found at %s (run pnpm install in web/): formulas will show as raw LaTeX", KATEX_DIR)
    has_mermaid = any(f.kind == "mermaid" for lec in lectures for f in _figures(lec))
    return _env.get_template("notes.html").render(
        doc_title=doc_title,
        lectures=lectures,
        cover=cover,
        tokens_css=_asset(TOKENS_CSS),
        katex_css=_asset(KATEX_DIR / "katex.min.css"),
        katex_js=_asset(KATEX_DIR / "katex.min.js"),
        has_mermaid=has_mermaid,
        mermaid_js=_asset(MERMAID_JS) if has_mermaid else None,
    )


def _figures(lecture: LectureView) -> list[FigureView]:
    return [f for s in lecture.sections for b in s.bullets for f in b.figures]


def build_lecture_html(lecture: LectureDetail, include_drafts: bool = True) -> str:
    return _render(lecture.summary.title, [lecture_view(lecture, include_drafts)], cover=None)


def build_module_html(lectures: list[LectureDetail], module_title: str, include_drafts: bool = True) -> str:
    views = [lecture_view(lec, include_drafts) for lec in lectures]
    cover = CoverView(
        title=module_title,
        lecture_count=len(views),
        verified_count=sum(v.status == LectureStatus.VERIFIED for v in views),
    )
    return _render(module_title, views, cover)


# ---------- running header / footer (Chromium print templates; inline styles only) ----------
def header_html(title: str, label: str, verified: bool) -> str:
    color = _token("--color-success-default", "green") if verified else _token("--color-warning-default", "orange")
    muted = _token("--color-text-tertiary", "gray")
    return (
        f'<div style="box-sizing:border-box;width:100%;padding:0 20mm;font-family:Inter,Helvetica,Arial,sans-serif;font-size:8pt;'
        f'display:flex;justify-content:space-between;color:{muted};">'
        f"<span>{html.escape(title)}</span>"
        f'<span style="color:{color};">{html.escape(label)}</span></div>'
    )


def footer_html() -> str:
    muted = _token("--color-text-tertiary", "gray")
    return (
        f'<div style="box-sizing:border-box;width:100%;padding:0 20mm;font-family:Inter,Helvetica,Arial,sans-serif;font-size:8pt;'
        f'display:flex;justify-content:space-between;color:{muted};">'
        f"<span>{html.escape(FOOTER_TEXT)}</span>"
        '<span>Page <span class="pageNumber"></span> of <span class="totalPages"></span></span></div>'
    )


def _allowed_url(url: str, page_uri: str) -> bool:
    """Only the temporary page itself and the known local assets (tokens.css, KaTeX css/js/fonts, mermaid.min.js) may load."""
    return url in (page_uri, MERMAID_JS.as_uri()) or url.startswith((KATEX_DIR.as_uri() + "/", TOKENS_CSS.as_uri()))


def _router(page_uri: str):  # noqa: ANN202
    async def _block_network(route: Route) -> None:
        if _allowed_url(route.request.url, page_uri):
            await route.continue_()
        else:
            await route.abort()

    return _block_network


async def html_to_pdf(document: str, header: str, footer: str) -> bytes:
    """Print an HTML document to an A4 PDF with headless Chromium. Only local files may load.

    At most two renders run at once, and each is cancelled after RENDER_TIMEOUT_S seconds (raises TimeoutError).
    """
    async with _RENDER_SLOTS:
        return await asyncio.wait_for(_print_pdf(document, header, footer), RENDER_TIMEOUT_S)


async def _print_pdf(document: str, header: str, footer: str) -> bytes:
    with tempfile.TemporaryDirectory(prefix="boardnotes-pdf-") as tmp:
        page_path = Path(tmp) / "notes.html"
        page_path.write_text(document, encoding="utf-8")
        async with async_playwright() as pw:
            # Chromium's own sandbox stays at Playwright's default (off): it needs user namespaces, which containers
            # often lack. The page is our own escaped HTML, and _router blocks every non-local request.
            browser = await pw.chromium.launch()
            try:
                context = await browser.new_context(color_scheme="light", java_script_enabled=True)
                await context.route("**/*", _router(page_path.as_uri()))
                page = await context.new_page()
                await page.goto(page_path.as_uri(), wait_until="load")
                await page.evaluate("document.fonts.ready.then(() => true)")
                try:  # Mermaid renders asynchronously; failures fall back to the board crop inside the page
                    await asyncio.wait_for(page.evaluate("Promise.resolve(window.__diagramsReady).then(() => true)"), DIAGRAMS_TIMEOUT_S)
                except Exception as exc:
                    log.warning("PDF: diagrams did not finish rendering: %s", exc)
                return await page.pdf(
                    format="A4",
                    print_background=True,
                    display_header_footer=True,
                    header_template=header,
                    footer_template=footer,
                    margin={"top": "22mm", "bottom": "20mm", "left": "20mm", "right": "20mm"},
                )
            finally:
                await browser.close()


# ---------- pipeline entry points ----------
async def render_pdf(lecture: LectureDetail, include_drafts: bool = True) -> bytes:
    """Pipeline stage (PdfRenderer): one lecture's notes as a PDF."""
    document = build_lecture_html(lecture, include_drafts)
    status = lecture.summary.status
    header = header_html(lecture.summary.title, status_label(status), status == LectureStatus.VERIFIED)
    return await html_to_pdf(document, header, footer_html())


async def render_module_pdf(lectures: list[LectureDetail], module_title: str, include_drafts: bool = True) -> bytes:
    """All lectures of a module in one PDF, with a cover and contents page (at most MAX_MODULE_LECTURES)."""
    if len(lectures) > MAX_MODULE_LECTURES:
        raise ValueError(f"a module PDF holds at most {MAX_MODULE_LECTURES} lectures, got {len(lectures)}")
    document = build_module_html(lectures, module_title, include_drafts)
    verified = sum(lec.summary.status == LectureStatus.VERIFIED for lec in lectures)
    header = header_html(module_title, f"{verified} of {len(lectures)} lectures verified", verified == len(lectures))
    return await html_to_pdf(document, header, footer_html())
